_PAIRS = tuple(sorted(TRANSLATIONS.items(), key=lambda pair: -len(pair[0])))
_LOCAL_PATH = re.compile(r'(?<![\w/])/(?:Users|Volumes|private|tmp|var|etc|opt|System|Library)/')


def _translate_text(value: str) -> str:
    for english, italian in _PAIRS:
        value = value.replace(english, italian)
    return value


def translate(value: str) -> str:
    # A path is data, even if one of its components resembles an interface label.
    output = []
    cursor = 0
    for match in _LOCAL_PATH.finditer(value):
        if match.start() < cursor:
            continue
        end = len(value)
        for separator in ('\n', ': ', '; ', ' (', ' [', ' — '):
            found = value.find(separator, match.start())
            if found != -1:
                end = min(end, found)
        output.append(_translate_text(value[cursor:match.start()]))
        output.append(value[match.start():end])
        cursor = end
    output.append(_translate_text(value[cursor:]))
    return ''.join(output)
